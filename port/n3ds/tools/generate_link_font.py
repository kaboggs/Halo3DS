"""Bake the OFL Oxanium font into a compact 4-bit Halo link-menu atlas."""

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
GLYPHS = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.:/+-?"
CELL = 16
SIDE = 128


# Kevin Boggs: main - New3DS integration.
def main():
    font = ImageFont.truetype(str(ROOT / "typography" / "Oxanium-Bold.ttf"), 14)
    atlas = Image.new("L", (SIDE, SIDE))
    draw = ImageDraw.Draw(atlas)
    for index, char in enumerate(GLYPHS):
        if char == " ":
            continue
        bounds = draw.textbbox((0, 0), char, font=font)
        width, height = bounds[2] - bounds[0], bounds[3] - bounds[1]
        x = (index % 8) * CELL + (CELL - width) // 2 - bounds[0]
        y = (index // 8) * CELL + (CELL - height) // 2 - bounds[1]
        draw.text((x, y), char, font=font, fill=255)
    pixels = atlas.tobytes()
    packed = bytes(((pixels[i] + 8) // 17 << 4) | ((pixels[i + 1] + 8) // 17)
                   for i in range(0, len(pixels), 2))
    output = ROOT / "include" / "engine_link_font_data.inl"
    lines = ["/* New3DS integration additions by Kevin Boggs.",
             " * Oxanium Bold (SIL Open Font License 1.1); generated by generate_link_font.py. */",
             f'static const char link_font_glyphs[] = "{GLYPHS}";',
             "static const unsigned char link_font_alpha4[] = {"]
    for start in range(0, len(packed), 16):
        lines.append(" " + ",".join(f"0x{b:02x}" for b in packed[start:start + 16]) + ",")
    lines.append("};")
    output.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(output, len(packed), "bytes")


if __name__ == "__main__":
    main()
